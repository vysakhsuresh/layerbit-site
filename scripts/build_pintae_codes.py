#!/usr/bin/env python3
"""Regenerate js/engines/pintae-codes.js, the PINT AE code lists used by the
PINT-AE Readiness Checker.

The lists are the ones published in OpenPeppol's PINT AE Billing resources
(docs.peppol.eu/poac/ae/pint-ae/resources.zip). They are read here from the
code-list data file of the MIT-licensed npm package uae-einvoice-mcp, which
extracts them from that zip; only the data literals are parsed (as JSON), no
JavaScript from the package is run.

Usage: python3 scripts/build_pintae_codes.py path/to/dist/lib/codelists-data.js
"""
import json, re, sys

LISTS = ["TAX_CATEGORY_CODES", "TAX_EXEMPTION_REASON_CODES", "CREDIT_NOTE_REASON_CODES", "PAYMENT_MEANS_CODES",
         "INVOICE_TYPE_CODES", "CREDIT_NOTE_TYPE_CODES", "ITEM_TYPE_CODES", "RCM_GOODS_TYPE_CODES", "CURRENCY_CODES",
         "COUNTRY_CODES", "UNIT_CODES", "ELECTRONIC_ADDRESS_SCHEMES"]


def main(src):
    text = open(src, encoding="utf-8").read()
    source = re.search(r'CODELIST_SOURCE = "([^"]+)"', text).group(1)
    out = {"source": source}
    for name in LISTS:
        m = re.search(r"export const " + name + r" = (\{.*?\n\});", text, re.S)
        if not m:
            sys.exit("missing " + name)
        out[name] = json.loads(m.group(1))
    body = json.dumps(out, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
    with open("js/engines/pintae-codes.js", "w", encoding="utf-8") as f:
        f.write("/* PINT AE code lists (" + source + "). Generated by scripts/build_pintae_codes.py; do not edit. */\n")
        f.write("(function (root, data) { if (typeof module === 'object' && module.exports) module.exports = data; else root.LBPintAECodes = data; })"
                "(typeof self !== 'undefined' ? self : this, " + body + ");\n")
    print({k: len(v) for k, v in out.items() if isinstance(v, dict)})


if __name__ == "__main__":
    main(sys.argv[1])
